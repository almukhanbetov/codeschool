В реальном алгоритме редко бывает только один сплошной цикл. Обычно есть обычные одиночные команды («выйти из дома»), а внутри — один или несколько циклов («повторить 10 раз: шаг вперёд»), а потом снова обычные команды («открыть дверь школы»). Важно уметь комбинировать это всё в одном алгоритме.

## Аналогия
Как поезд с одним особым вагоном-гармошкой (цикл, который «растягивается» на много повторений), а спереди и сзади — обычные вагоны (одиночные команды). Весь поезд — это один алгоритм.

## Пример
Алгоритм «дойти до школы»: 1) выйти из подъезда (обычная команда), 2) повторить 20 раз: шаг вперёд (цикл), 3) перейти дорогу (обычная команда), 4) повторить 10 раз: шаг вперёд (ещё один цикл), 5) зайти в школу (обычная команда).

## Практика
Составь алгоритм из 5 шагов, где есть минимум 2 обычные команды и минимум 1 цикл (в формате «Повтори N раз: [действие]»), например, алгоритм «убрать игрушки».

